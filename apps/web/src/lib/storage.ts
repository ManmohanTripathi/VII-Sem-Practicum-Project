import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { randomBytes } from "node:crypto";

// Local file storage for message audio. STORAGE_DIR defaults to apps/web/storage (git-ignored).
// Swap for S3/GCS when deploying to more than one server.

function root() {
  return process.env.STORAGE_DIR || path.join(process.cwd(), "storage");
}

const EXT: Record<string, string> = {
  "audio/mpeg": "mp3",
  "audio/mp3": "mp3",
  "audio/wav": "wav",
  "audio/x-wav": "wav",
  "audio/wave": "wav",
  "audio/mp4": "m4a",
  "audio/x-m4a": "m4a",
  "audio/m4a": "m4a",
  "audio/aac": "aac",
  "audio/webm": "webm",
  "audio/ogg": "ogg",
};

export function extensionFor(mime: string, fallbackName?: string) {
  const base = mime.split(";")[0].trim().toLowerCase();
  return EXT[base] ?? fallbackName?.split(".").pop()?.toLowerCase().replace(/[^a-z0-9]/g, "") ?? "bin";
}

export function mimeFor(file: string) {
  const ext = file.split(".").pop();
  return { mp3: "audio/mpeg", wav: "audio/wav", m4a: "audio/mp4", aac: "audio/aac", webm: "audio/webm", ogg: "audio/ogg" }[ext ?? ""] ?? "application/octet-stream";
}

export async function saveAudio(data: ArrayBuffer | Buffer, ext: string): Promise<string> {
  const dir = path.join(root(), "messages");
  await mkdir(dir, { recursive: true });
  const name = `${Date.now()}-${randomBytes(8).toString("hex")}.${ext}`;
  await writeFile(path.join(dir, name), Buffer.from(data as ArrayBuffer));
  return name;
}

export async function readAudio(name: string): Promise<Buffer> {
  // Names are generated by saveAudio; refuse anything that could escape the folder.
  if (!/^[\w.-]+$/.test(name)) throw new Error("bad file name");
  return readFile(path.join(root(), "messages", name));
}
